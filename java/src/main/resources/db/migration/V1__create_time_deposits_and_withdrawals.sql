-- Schema for README "Database Setup".
--
-- Naming: the README names the table/columns in camelCase (timeDeposits, planType, timeDepositId).
-- PostgreSQL folds unquoted identifiers to lower case (timeDeposits -> timedeposits), and keeping the
-- camelCase would require double quotes in every migration and query. The PostgreSQL convention,
-- snake_case, is used instead; the API keeps the README's camelCase field names.
--
-- Ids: identity columns, so rows inserted by other systems get increasing ids without coordination
-- (the keyset cursors of the balance update and the GET pagination rely on that). BY DEFAULT still
-- allows explicit ids in seeds and tests.

CREATE TABLE time_deposits (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_type                VARCHAR       NOT NULL,
    days                     INTEGER       NOT NULL,
    balance                  NUMERIC(19,2) NOT NULL,
    -- Addition beyond the README schema (not exposed by the API): business date on which monthly
    -- interest was last applied; NULL = never. Makes the balance update idempotent (PLAN.md §3).
    last_interest_applied_on DATE
);

CREATE TABLE withdrawals (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_deposit_id INTEGER       NOT NULL REFERENCES time_deposits (id),
    amount          NUMERIC(19,2) NOT NULL,
    date            DATE          NOT NULL
);

-- PostgreSQL does not index foreign keys automatically; the GET joins withdrawals by deposit.
CREATE INDEX withdrawals_time_deposit_id_idx ON withdrawals (time_deposit_id);
